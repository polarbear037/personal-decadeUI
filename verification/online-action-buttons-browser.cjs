const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const { server, chromium, seed } = require('./online-player-tips-browser.cjs');
seed.characters = ['standard'];
seed.cards = ['standard', 'extra'];
seed.extension_十周年UI_enableRecastInteraction = true;

(async () => {
 await new Promise(resolve => server.listen(39321, '127.0.0.1', resolve));
 const browser = await chromium.launch({ channel: 'msedge', headless: true });
 const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
 const errors = [], requests = [];
 page.on('pageerror', error => { errors.push(error.stack || String(error)); console.error('BROWSER_ERROR', error.message); });
 page.on('dialog', async dialog => { console.log('DIALOG', dialog.message()); await dialog.accept(); });
 page.on('response', response => { if (response.status() >= 400) requests.push([response.status(), response.url()]); });
 try {
  await page.goto(`http://127.0.0.1:${server.address().port}/player-tips-probe`);
  console.log('BOOTED');
  await page.waitForFunction(async () => { const { game, ui } = await import('/noname.js'); return game.players.length > 1 && window.decadeUI && ui.arena && Array.isArray(ui.dialogs) && ui.create.confirm; }, null, { timeout: 45000 });
  await page.waitForTimeout(1200);
  console.log('READY');
  const setup = await page.evaluate(async () => {
   const { game, ui, lib, get, _status } = await import('/noname.js');
   const { Content } = await import('/noname/library/element/content.js');
   const { syncOnlineActionButtons } = await import('/extension/十周年UI/src/ui/online-action-buttons.js');
   Object.assign(window, { game, ui, lib, get, _status, Content, syncOnlineActionButtons });
   game.pause(); game.pause2();
   for (const dialog of [...ui.dialogs]) dialog.close();
   for (const control of [...ui.controls]) control.close();
   document.querySelector('.decade-welcome-overlay')?.remove();
   ui.arena.classList.remove('choose-character');
   game.me = game.players[0]; window.other = game.players[1];
   game.me.init('liubei'); other.init('guanyu');
   _status.gameStarted = true; _status.over = false; _status.currentPhase = game.me; _status.auto = false;
   lib.config.auto_confirm = false;
   const tiesuo = game.createCard('tiesuo', 'club', 12), sha = game.createCard('sha', 'spade', 8), wuxie = game.createCard('wuxie', 'spade', 11);
   game.me.directgain([tiesuo, sha, wuxie]);
   window.testCards = { tiesuo, sha, wuxie };
   window.beginPhase = async () => {
    game.uncheck(); ui.confirm?.close();
    for (const dialog of [...ui.dialogs]) dialog.close();
    const event = game.me.chooseToUse({ type: 'phase' });
    _status.eventManager.setStatusEvent(event, true);
    await Content.chooseToUse[0](event, null, game.me);
    window.choice = event;
   };
   window.nativeClick = (fn, node) => { _status.clicked = false; fn.call(node); };
   window.geometry = () => {
    syncOnlineActionButtons();
    const read = node => node && ({ text: node.textContent, display: getComputedStyle(node).display, background: getComputedStyle(node).backgroundImage, rect: node.getBoundingClientRect().toJSON(), first: node === ui.confirm.firstChild, last: node === ui.confirm.lastChild });
    return { ok: read(ui.confirm.node.ok), cancel: read(ui.confirm.node.cancel), recast: read(ui.confirm.recastButton), ignore: read(ui.tempnowuxie), scale: ui.confirm.node.ok.offsetWidth / 207 };
   };
   await beginPhase();
   return { nativeRecastEnabled: lib.skill._recasting.filter(choice, game.me), replacedRecast: !!lib.skill._decadeUI_recastable_recast, none: geometry() };
  });
  assert.equal(setup.nativeRecastEnabled, true);
  assert.equal(setup.replacedRecast, false);
  assert.equal(setup.none.recast.display, 'none');
  const selection = await page.evaluate(() => {
   nativeClick(ui.click.card, testCards.sha); const sha = geometry();
   nativeClick(ui.click.card, testCards.sha);
   nativeClick(ui.click.card, testCards.tiesuo); const iron = geometry();
   const target = game.players.find(player => player.classList.contains('selectable'));
   if (!target) throw Error('No target for selected tiesuo');
   nativeClick(ui.click.target, target); const withTarget = geometry();
   return { sha, iron, withTarget, targets: ui.selected.targets.length, duplicates: document.querySelectorAll('.skill-control [data-id="_recasting"]').length };
  });
  assert.equal(selection.sha.recast.display, 'none');
  assert.equal(selection.iron.recast.display, 'flex');
  assert.equal(selection.iron.ok.text, '确定');
  assert(selection.targets > 0);
  assert.equal(selection.withTarget.recast.display, 'flex');
  assert.equal(selection.duplicates, 0);
  const g = selection.iron;
  assert(g.ok.first && g.cancel.last, 'native first/last button contract');
  assert(Math.abs(g.recast.rect.width - 142 * g.scale) < 1);
  const center = rect => rect.x + rect.width / 2;
  assert(Math.abs(center(g.ok.rect) - center(g.recast.rect) - 251 * g.scale) < 1);
  await page.waitForTimeout(550);
  await page.screenshot({ path: path.join(__dirname, 'online-action-recast.png') });
  await page.locator('.online-recast-button').click();
  const recast = await page.evaluate(() => {
   game.pause();
   return { skill: choice.result?.skill, bool: choice.result?.bool, cards: choice.result?.cards?.map(card => card.name), targets: choice.result?.targets?.length };
  });
  assert.equal(recast.skill, '_recasting');
  assert.equal(recast.bool, true);
  assert.deepEqual(recast.cards, ['tiesuo']);
  assert.equal(recast.targets, 0);

  const wuxie = await page.evaluate(async () => {
   game.uncheck(); ui.confirm?.close();
   const parent = new lib.element.GameEvent('useCard', false); parent.id = 'ol-wuxie-test';
   const trigger = new lib.element.GameEvent('useCardToBegin', false); trigger.parent = parent;
   trigger.card = { name: 'nanman' }; trigger.player = other; trigger.target = other;
   trigger.targets = [other, game.me]; trigger.num = 0;
   const event = game.me.chooseToUse({ type: 'wuxie', state: 1, filterCard: card => card.name === 'wuxie', prompt: '是否使用【无懈可击】？' });
   event._trigger = trigger;
   event.info_map = { player: other, target: other, targets: trigger.targets, card: trigger.card };
   _status.eventManager.setStatusEvent(event, true);
   ui.tempnowuxie = ui.create.control('不无懈南蛮', ui.click.tempnowuxie, 'stayleft');
   ui.tempnowuxie._origin = parent.id;
   await Content.chooseToUse[0](event, null, game.me);
   window.wuxieCase = { event, trigger, parent };
   await document.fonts.ready;
   await new Promise(resolve => requestAnimationFrame(resolve));
   return { nativeCallback: ui.tempnowuxie.custom === ui.click.tempnowuxie, before: lib.filter.wuxieSwap(event), geometry: geometry() };
  });
  assert.equal(wuxie.nativeCallback, true);
  assert.equal(wuxie.before, false);
  assert.equal(wuxie.geometry.ignore.text, '本次不无懈');
  const ig = wuxie.geometry;
  assert(Math.abs(ig.ignore.rect.width - 177 * ig.scale) < 1);
  assert(Math.abs(center(ig.ignore.rect) - center(ig.cancel.rect) - 250 * ig.scale) < 1);
  assert(ig.ignore.rect.x >= ig.cancel.rect.right, 'ignore overlaps cancel');
  await page.waitForTimeout(550);
  await page.screenshot({ path: path.join(__dirname, 'online-action-wuxie.png') });
  await page.locator('.online-tempnowuxie').click();
  const skip = await page.evaluate(() => {
   game.pause();
   const { event, trigger } = wuxieCase;
   const clicked = { glow: ui.tempnowuxie.classList.contains('glow'), result: event.result?.bool, other: lib.filter.wuxieSwap(event), display: getComputedStyle(ui.tempnowuxie).display };
   trigger.target = game.me; event.info_map.target = game.me;
   const self = lib.filter.wuxieSwap(event);
   ui.wuxie.classList.add('glow'); const global = lib.filter.wuxieSwap(event); ui.wuxie.classList.remove('glow');
   trigger.target = other; event.info_map.target = other;
   const afterSelf = lib.filter.wuxieSwap(event);
   event.state = -1; const counter = lib.filter.wuxieSwap(event); event.state = 1;
   ui.tempnowuxie._origin = 'another-card'; const different = lib.filter.wuxieSwap(event);
   ui.tempnowuxie._origin = wuxieCase.parent.id;
   return { clicked, self, global, afterSelf, counter, different };
  });
  assert.deepEqual(skip, { clicked: { glow: true, result: false, other: true, display: 'none' }, self: false, global: true, afterSelf: true, counter: false, different: false });
  const selfPrompt = await page.evaluate(async () => {
   const { trigger } = wuxieCase;
   trigger.target = game.me; trigger.num = 0;
   const event = game.me.chooseToUse({ type: 'wuxie', state: 1, filterCard: card => card.name === 'wuxie', prompt: '群体锦囊对你生效，是否使用【无懈可击】？' });
   event._trigger = trigger;
   event.info_map = { player: other, target: game.me, targets: trigger.targets, card: trigger.card };
   _status.eventManager.setStatusEvent(event, true);
   await Content.chooseToUse[0](event, null, game.me);
   return { result: event.result, paused: _status.paused, confirm: !!ui.confirm, prompt: event.dialog?.textContent, selectable: testCards.wuxie.classList.contains('selectable') };
  });
  assert.notEqual(selfPrompt.result?.bool, false);
  assert.equal(selfPrompt.paused, true);
  assert.equal(selfPrompt.confirm, true);
  assert.equal(selfPrompt.selectable, true);
  assert.equal(await page.locator('.online-tempnowuxie').isVisible(), false, '本次不无懈点击后不能随提示刷新重新出现');
  // 下一张锦囊创建的新控件应正常显示，并继续使用原有缩放定位。
  await page.evaluate(() => {
   ui.tempnowuxie.close();
   ui.tempnowuxie = ui.create.control('不无懈万箭', ui.click.tempnowuxie, 'stayleft');
   ui.tempnowuxie._origin = 'next-card';
   syncOnlineActionButtons();
  });
  assert.equal(await page.locator('.online-tempnowuxie:not(.glow)').isVisible(), true);
  await page.setViewportSize({ width: 1280, height: 800 });
  await page.evaluate(() => { game.documentZoom = 1.25; ui.updatez(); document.body.style.width = '80%'; document.body.style.height = '80%'; });
  await page.waitForTimeout(100);
  const zoom = await page.evaluate(() => geometry());
  const actualScale = zoom.ok.rect.width / 207;
  assert.equal(await page.evaluate(() => Number(getComputedStyle(document.body).zoom)), 1.25);
  assert(Math.abs(zoom.ignore.rect.width - 177 * actualScale) < 1);
  assert(Math.abs(center(zoom.ignore.rect) - center(zoom.cancel.rect) - 250 * actualScale) < 1);
  assert(zoom.ignore.rect.x >= zoom.cancel.rect.right);
  assert(zoom.ignore.rect.right <= 1280);
  const controls = await page.evaluate(() => [...ui.control.children].map(node => ({ class: node.className, text: node.textContent, html: node.outerHTML.slice(0, 500), rect: node.getBoundingClientRect().toJSON() })));
  const result = { setup, selection, recast, wuxie, skip, selfPrompt, zoom, controls, errors, requests };
  fs.writeFileSync(path.join(__dirname, 'online-action-buttons-results.json'), JSON.stringify(result, null, 2));
  assert.deepEqual(errors, []);
  assert(!requests.some(([, url]) => /seatui_btns_|FZLBGBK/.test(url)), 'new button asset failed to load');
  console.log('ONLINE_ACTION_BUTTONS_OK', JSON.stringify({ recast, skip, selfPrompt, errors, requests }));
 } finally { await browser.close(); server.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; server.close(); });
