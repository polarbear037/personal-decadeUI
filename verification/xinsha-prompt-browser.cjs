const fs = require("node:fs");
const path = require("node:path");
const { installNativeHarness, server, chromium, assert, script } = require("./optimized-prompt-browser.cjs");

async function run() {
	await new Promise(resolve => server.listen(0, "127.0.0.1", resolve));
	const origin = `http://127.0.0.1:${server.address().port}`;
	const browser = await chromium.launch({ channel: "msedge", headless: true });
	const page = await browser.newPage({ viewport: { width: 1500, height: 800 } });
	const errors = [];
	page.on("pageerror", error => errors.push(error.message));
	try {
		await installNativeHarness(page, origin, false);
		await page.addStyleTag({ url: `${origin}/extension/十周年UI/ui/styles/fonts-xinsha.css` });
		await page.addStyleTag({ content: "html,body,#window,#arena{width:100%;height:100%;margin:0}#arena{position:relative;background:#30291f}body{--yjcm-unit:1px} .hand-tip{position:absolute}" });
		await page.addScriptTag({ content: script("extension/十周年UI/src/config/handlers/appearance-handlers.js", "window.onOptimizePromptClick=m;") });
		const result = await page.evaluate(async () => {
			if (!document.getElementById("window")) {
				const windowNode = document.createElement("div");
				windowNode.id = "window";
				ui.arena.before(windowNode);
				windowNode.appendChild(ui.arena);
			}
			document.body.dataset.style = "othersOff";
			lib.config.extension_十周年UI_newDecadeStyle = "othersOff";
			lib.config.extension_十周年UI_simplifySkillPrompt = false;
			Object.assign(lib.translate, { sha: "杀", shan: "闪", tao: "桃", wuzhong: "无中生有", zhiheng: "制衡", luoshen: "洛神", guanyu: "关羽", sunquan: "孙权", nanman: "南蛮入侵", wuxie: "无懈可击" });
			game.me.name = "sunquan";
			ui.selected = { cards: [], targets: [], buttons: [] };
			game.players = [game.me, { name: "guanyu" }];
			get.skillTranslation = skill => lib.translate[skill] || skill;
			get.skillInfoTranslation = skill => lib.translate[skill + "_info"] || "";
			get.card = () => lib.skill[_status.event?.skill]?.viewAs || ui.selected.cards[0];
			lib.card.sha = { selectTarget: [1, 1] };
			lib.card.wuzhong = { notarget: true };
			lib.skill.zhiheng = { selectCard: [1, -1], selectTarget: [0, 0] };
			lib.translate.zhiheng_info = xinshaPromptEntries.find(entry => entry.id === 53).description;
			const saved = [];
			game.saveConfig = (key, value) => { lib.config[key] = value; saved.push(value); };
			lib.config[optimizePromptKey] = true;
			migrateOptimizedPromptConfig();
			const migration = { value: lib.config[optimizePromptKey], style: getOptimizedPromptStyle() };
			lib.config[optimizePromptKey] = false;
			migrateOptimizedPromptConfig();
			migration.disabled = lib.config[optimizePromptKey];
			window.readXinshaTip = () => {
				const tip = [...ui.arena.querySelectorAll(".decade-optimized-hand-tip")].find(node => !node.closed && !node.classList.contains("hidden"));
				if (!tip) return null;
				const style = getComputedStyle(tip);
				return { main: tip.querySelector(".decade-official-main")?.textContent, mode: tip.dataset.optimizedPromptStyle, id: tip.dataset.officialSkillId, color: style.color, size: style.fontSize, bottom: style.bottom, font: style.fontFamily, spans: [...tip.querySelectorAll("span span")].map(node => ({ text: node.textContent, color: getComputedStyle(node).color, font: getComputedStyle(node).fontFamily, size: getComputedStyle(node).fontSize, stroke: getComputedStyle(node).webkitTextStroke })) };
			};
			const phase = { name: "phaseUse" };
			const event = { name: "chooseToUse", type: "phase", player: game.me, isMine: () => true, getParent: () => phase, selectTarget: () => undefined };
			_status.event = event;
			_status.imchoosing = true;
			ui.selected.cards = [];
			ui.selected.targets = [];
			onOptimizePromptClick("xinsha");
			await document.fonts.ready;
			const phaseTip = readXinshaTip();
			ui.selected.cards = [{ name: "sha" }];
			refreshOptimizedPrompt();
			const sha = readXinshaTip();
			ui.selected.cards = [{ name: "wuzhong" }];
			refreshOptimizedPrompt();
			const wuzhong = readXinshaTip();
			ui.selected.cards = [];
			event.skill = "zhiheng";
			refreshOptimizedPrompt();
			await document.fonts.ready;
			const skill = readXinshaTip();
			_status.event = { name: "chooseToRespond", player: game.me, isMine: () => true, respondTo: [game.players[1], { name: "sha" }], selectCard: [1, 1] };
			refreshOptimizedPrompt();
			const response = readXinshaTip();
			_status.event.selectCard = [2, 2];
			_status.event.prompt = "请打出两张闪响应杀";
			refreshOptimizedPrompt();
			const doubleResponse = readXinshaTip();
			_status.event = { name: "chooseToUse", type: "dying", dying: { name: "guanyu", hp: -1 }, player: game.me, isMine: () => true };
			refreshOptimizedPrompt();
			const dying = readXinshaTip();
			_status.event = { name: "chooseToUse", type: "wuxie", player: game.me, isMine: () => true, info_map: { state: 1, player: game.players[1], target: game.me, card: { name: "nanman" } } };
			refreshOptimizedPrompt();
			const wuxie = readXinshaTip();
			_status.event = { name: "chooseTarget", player: game.me, isMine: () => true, prompt: '选择曹操的两名敌人', selectTarget: [2, 2] };
			refreshOptimizedPrompt();
			const custom = readXinshaTip();
			_status.event = event;
			delete event.skill;
			const dialog = ui.create.dialog("原生操作提示");
			event.dialog = dialog;
			onOptimizePromptClick("off");
			const disabled = { tip: readXinshaTip(), hidden: dialog.dataset.decadeOptimizedPrompt || "", nativeDisplay: getComputedStyle(dialog.content.firstElementChild).display };
			dialog.close();
			delete event.dialog;
			onOptimizePromptClick("online");
			const online = readXinshaTip();
			const onlinePopup = ui.arena.dataset.decadeOfficialPlayerPopups;
			onOptimizePromptClick("xinsha");
			const xinshaPopup = ui.arena.dataset.decadeOfficialPlayerPopups || "";
			const unmapped = buildXinshaPrompt({ ...event, skill: "custom", name: "chooseTarget", selectTarget: [2, 2] }, "为本扩展挑选两名角色", "custom");
			return { migration, saved, phaseTip, sha, wuzhong, skill, response, doubleResponse, dying, wuxie, custom, disabled, online, onlinePopup, xinshaPopup, unmapped };
		});
		assert.deepEqual(result.migration, { value: "online", style: "online", disabled: "off" });
		assert.equal(result.phaseTip.main, "出牌阶段，请选择一张卡牌");
		assert.equal(result.phaseTip.mode, "xinsha");
		assert.equal(result.phaseTip.color, "rgb(254, 240, 201)");
		assert.match(result.phaseTip.font, /dui-xinsha-prompt-label/);
		assert.equal(result.phaseTip.size, "28px");
		assert.equal(result.phaseTip.bottom, "299px");
		assert.equal(result.sha.main, "选择1名目标角色");
		assert.equal(result.wuzhong.main, "使用这张牌（摸2张牌）");
		assert.equal(result.skill.main, "请选择你要“制衡”的牌");
		const skillSpan = result.skill.spans.find(span => span.text.includes("制衡"));
		assert.equal(skillSpan.color, "rgb(163, 240, 48)");
		assert.match(skillSpan.font, /dui-xinsha-prompt-skill/);
		assert.equal(skillSpan.size, "32px");
		assert.match(skillSpan.stroke, /rgb\(97, 65, 49\)/);
		assert.equal(result.response.main, "关羽对你使用了【杀】，请使用一张【闪】");
		assert.equal(result.response.spans.find(span => span.text === "关羽").color, "rgb(255, 225, 0)");
		assert.equal(result.response.spans.find(span => span.text.includes("【闪】")).color, "rgb(255, 217, 121)");
		assert.equal(result.doubleResponse.main, "请打出两张闪响应杀");
		assert.equal(result.dying.main, "关羽濒死，需要2个【桃】，是否对其使用【桃】？");
		assert.equal(result.wuxie.main, "为你使用一张【无懈可击】");
		assert.equal(result.custom.main, "选择曹操的两名敌人");
		assert.equal(result.disabled.tip, null);
		assert.equal(result.disabled.hidden, "");
		assert.notEqual(result.disabled.nativeDisplay, "none");
		assert.equal(result.online.mode, "online");
		assert.equal(result.onlinePopup, "true");
		assert.equal(result.xinshaPopup, "");
		assert.equal(result.unmapped.main, "为本扩展挑选两名角色");
		assert.equal(result.unmapped.official, null);
		await page.evaluate(() => { _status.event.skill = "zhiheng"; refreshOptimizedPrompt(); });
		await page.screenshot({ path: path.join(__dirname, "xinsha-prompt-browser.png") });
		assert.deepEqual(errors, []);
		fs.writeFileSync(path.join(__dirname, "xinsha-prompt-results.json"), JSON.stringify({ ...result, errors }, null, 2));
		console.log("XINSHA_PROMPT_OK", JSON.stringify({ phase: result.phaseTip.main, skill: result.skill.main, response: result.response.main, migration: result.migration, errors }));
	} finally {
		await browser.close();
		await new Promise(resolve => server.close(resolve));
	}
}

run().catch(error => { console.error(error); process.exitCode = 1; });
